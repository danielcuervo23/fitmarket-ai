import { createHash } from "node:crypto";
import type { Recipe } from "../../supabase/functions/_shared/recipes/types.ts";

// Turns the validated recipes into the source of
// supabase/functions/_shared/recipes/library.generated.ts. Pure and
// deterministic: same recipes in any order give the same text.

const byId = (a: Recipe, b: Recipe) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0);

/** First 12 hex chars of the SHA-256 of the recipes' JSON (already sorted by id). */
function libraryVersion(sorted: readonly Recipe[]): string {
  return createHash("sha256").update(JSON.stringify(sorted)).digest("hex").slice(0, 12);
}

export function buildLibraryModule(recipes: readonly Recipe[]): string {
  const sorted = [...recipes].sort(byId);
  return [
    "// GENERATED by scripts/recipes/build-library.ts from data/recipes/*.json.",
    "// Do not edit by hand: fix the recipe file, then run `node scripts/recipes/build-library.ts`.",
    'import type { Recipe } from "./types.ts";',
    "",
    "// Frozen once at load: every request shares these objects, so nobody may change them.",
    "function deepFreeze<T>(value: T): T {",
    '  if (value !== null && typeof value === "object") {',
    "    for (const child of Object.values(value)) deepFreeze(child);",
    "    Object.freeze(value);",
    "  }",
    "  return value;",
    "}",
    "",
    `export const RECIPE_LIBRARY_VERSION = "${libraryVersion(sorted)}";`,
    "",
    `export const RECIPES: readonly Recipe[] = deepFreeze<Recipe[]>(${JSON.stringify(sorted, null, 2)});`,
    "",
  ].join("\n");
}
